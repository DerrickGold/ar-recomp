bool SimBackgroundMountainSilhouette_Lookup(
    uint8_t tile, int pixel_x, int pixel_y, bool *opaque) {
  if (!opaque || pixel_x < 0 || pixel_x >= 16 ||
      pixel_y < 0 || pixel_y >= 16)
    return false;
  for (size_t at = 0;
       at < sizeof(kSilhouettes) / sizeof(kSilhouettes[0]); at++) {
    if (kSilhouettes[at].tile != tile) continue;
    *opaque = (kSilhouettes[at].rows[pixel_y] & (1u << pixel_x)) != 0;
    return true;
  }
  return false;
}
