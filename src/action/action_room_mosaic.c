#include "action_room_mosaic.h"

static const uint8_t kPatterns[3][22] = {
  {0xb3,0x5e,0x68,0x84,0x86,0x06,0x82,0x28,0xc2,0x12,0x5b,0x2c,0xb1,0xc5,0xc2,0x84,0x60,0xc4,0xd5,0xf8,0xdb,0x7d},
  {0xb3,0x5e,0x60,0x04,0x06,0x06,0x82,0x28,0xc2,0x12,0x5b,0x2c,0xb1,0xc5,0xc2,0x80,0x68,0xc4,0xc5,0xf8,0xdb,0x7d},
  {0xb3,0x5e,0x68,0x86,0x86,0x06,0x82,0x28,0xc2,0x12,0x5b,0x2c,0xb1,0xc5,0xc2,0x84,0x60,0xc6,0xd5,0xf8,0xdb,0x7d},
};
bool ActionRoomMosaic_Bit(uint8_t pattern,unsigned index,uint8_t *out) {
  if (!out || pattern>=kActionRoomMosaicPatterns || index>=kActionRoomMosaicWindow) return false;
  *out=(uint8_t)((kPatterns[pattern][index>>3]>>(index&7))&1);return true;
}
bool ActionRoomMosaic_Project(ActionRoomScene *scene,uint8_t pattern) {
  if (!scene || pattern>=kActionRoomMosaicPatterns) return false;
  if (scene->raster_effect!=kActionRoomRaster_Bg2MosaicWave) return true;
  if (!scene->have_raster_mosaic_wave_window) return false;
  for (unsigned i=0;i<kActionRoomMosaicWindow;++i)
    ActionRoomMosaic_Bit(pattern,i,&scene->raster_mosaic_wave_window[i]);
  return true;
}
