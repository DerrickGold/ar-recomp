bool ActRaiserStorySnapshot_Capture(CpuState *cpu, uint8_t out[kActRaiserSramSize]) {
  if (!cpu || !out) return false;
  for (unsigned i = 0; i < kActRaiserSramSize; ++i) out[i] = cpu_read8(cpu, 0x70, i);
  for (unsigned n = 0; n < sizeof(kCopies) / sizeof(kCopies[0]); ++n) {
    const StoryCopy *copy = &kCopies[n];
    for (unsigned i = 0; i < copy->length; ++i)
      out[copy->destination + i] = cpu_read8(cpu, copy->bank, copy->source + i);
  }
  Save_RecomputeChecksum(out);
  return true;
}
