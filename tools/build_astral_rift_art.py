#!/usr/bin/env python3
"""Embed the authored Astral Rift PNGs for identical native/WASM offline assets.

No runtime filesystem, browser fetch or platform image loader is required.
Run after replacing an asset; --check verifies the checked-in packed data.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ("nebula", "clouds", "ruins", "floor")
OUTPUT = ROOT / "src/diorama/astral_rift_art.inc"


def packed_art():
    lines = ["/* Generated by tools/build_astral_rift_art.py. Do not edit. */"]
    for name in ASSETS:
        data = (ROOT / f"assets/death-heim/astral-{name}.png").read_bytes()
        lines.append(f"static const unsigned char kAstral{name.title()}Png[] = {{")
        lines.extend("  " + ",".join(f"0x{x:02x}" for x in data[i:i+24]) + ","
                     for i in range(0, len(data), 24))
        lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = packed_art()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit("Astral Rift art is stale; run tools/build_astral_rift_art.py")
    else:
        OUTPUT.write_text(text)
    print(f"Astral Rift: {len(ASSETS)} embedded PNG assets verified")
