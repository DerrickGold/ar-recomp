"""Regenerate reviewed native artwork contracts for Northwall tree side halls."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
name = 'northwall-tree-side-materials.json'
data = json.loads((root / 'assets/environments' / name).read_text())
lines = [f'/* Generated by tools/generate_trunk_side_materials.py from {name}. */',
         'static const TrunkSideProfile kTrunkSideProfiles[] = {']
seen = set()
for record in sorted(data['materials'], key=lambda item: item['key']):
    key = int(record['key'], 16)
    assert key not in seen
    seen.add(key)
    masks = [record[field] for field in ('solid_colors', 'rear_colors', 'snow_colors', 'snow_face_colors')]
    assert all(len(mask) == 4 and all(type(v) is int and 0 <= v <= 65535 and not v & 1 for v in mask) for mask in masks)
    assert all(not (a & b) and not (c & ~a) and not (d & ~c) and not (d & ~0xf000)
               for a, b, c, d in zip(*masks))
    if any(masks[3]):
        assert record.get('snow_face_reason') and record['role'] == 'snow_branch_body'
    assert type(record['native_slope']) is bool and record['role']
    rooms = 0
    for room, terrain, native_id in record['origins']:
        assert room in (6, 7) and terrain in (0, 1, 2) and 0 <= native_id < 256
        rooms |= 1 << room
    text = ','.join('{' + ','.join(map(str, mask)) + '}' for mask in masks)
    lines.append(f'  {{UINT64_C(0x{key:016x}),{rooms},{int(record["native_slope"])},{text}}},')
lines.append('};')
donor = data['snow_donor']
assert donor['crop'] == [2, 2, 8] and donor['palette'] == 4 and donor['opaque_indices'] == [13, 14, 15]
lines.append(f'static const uint64_t kTrunkSideSnowKey=UINT64_C(0x{int(donor["key"],16):016x});')
output = root / 'src/action/action_trunk_side_materials.inc'
text = '\n'.join(lines) + '\n'
if args.check:
    if not output.exists() or output.read_text() != text:
        raise SystemExit(f'{output}: stale; run tools/generate_trunk_side_materials.py')
else:
    output.write_text(text)
print(name, len(seen), 'reviewed side-hall contracts')
