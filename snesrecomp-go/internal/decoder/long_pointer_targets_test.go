package decoder

import (
	"reflect"
	"testing"
)

func TestLiteralLongPointerByteLanes(t *testing.T) {
	for _, tt := range []struct {
		name string
		code []byte
		want []uint32
	}{
		{"low word wins middle byte", []byte{0xa9, 0x83, 0, 0x8d, 0x41, 0, 0xa9, 0x10, 0x82, 0x8d, 0x40, 0, 0x60}, []uint32{0x8210}},
		{"high word wins middle byte", []byte{0xa9, 0x10, 0x82, 0x8d, 0x40, 0, 0xa9, 0x83, 0, 0x8d, 0x41, 0, 0x60}, []uint32{0x8310}},
		{"three byte stores", []byte{0xe2, 0x20, 0xa9, 0x10, 0x85, 0x40, 0xa9, 0x82, 0x85, 0x41, 0xa9, 0, 0x85, 0x42, 0x60}, []uint32{0x8210}},
		{"X Y word stores", []byte{0xa2, 0x10, 0x82, 0x8e, 0x40, 0, 0xa0, 0x83, 0, 0x8c, 0x41, 0, 0x60}, []uint32{0x8310}},
		{"unknown low lane", []byte{0xa9, 0x82, 0, 0x8d, 0x41, 0, 0xa5, 0x10, 0x8d, 0x40, 0, 0x60}, nil},
		{"call separates writers", []byte{0xa9, 0x82, 0, 0x8d, 0x41, 0, 0x20, 0, 0x84, 0xa9, 0x10, 0x82, 0x8d, 0x40, 0, 0x60}, nil},
		{"hardware write separates writers", []byte{0xa9, 0x82, 0, 0x8d, 0x41, 0, 0x8d, 0x0b, 0x42, 0xa9, 0x10, 0x82, 0x8d, 0x40, 0, 0x60}, nil},
		{"wrapping write separates writers", []byte{0xa9, 0x82, 0, 0x8d, 0x41, 0, 0x8d, 0xff, 0xff, 0xa9, 0x10, 0x82, 0x8d, 0x40, 0, 0x60}, nil},
		{"incomplete pointer", []byte{0xa9, 0x10, 0x82, 0x8d, 0x40, 0, 0x60}, nil},
	} {
		t.Run(tt.name, func(t *testing.T) {
			image := bank0(map[uint16][]byte{0x8000: tt.code, 0x8100: {0xdc, 0x40, 0}, 0x8210: {0x6b}, 0x8310: {0x6b}, 0x8400: {0x60}})
			graphs := []*Graph{mustDecode(t, image, 0x8000, 0, 0), mustDecode(t, image, 0x8100, 0, 0)}
			if got := LiteralLongPointerTargets(image, graphs, nil); !reflect.DeepEqual(got, tt.want) {
				t.Fatalf("got %X want %X", got, tt.want)
			}
			if got := LiteralLongPointerTargets(image, graphs, []DataRegion{{Bank: 0, Start: 0x8210, End: 0x8311}}); len(got) != 0 {
				t.Fatalf("authored data admitted: %X", got)
			}
			if got := LiteralLongPointerTargets(image, graphs[:1], nil); len(got) != 0 {
				t.Fatalf("no JML consumer: %X", got)
			}
		})
	}
}

func TestLiteralLongPointerDoesNotMixIndependentWriters(t *testing.T) {
	image := bank0(map[uint16][]byte{0x8000: {0xa9, 0x10, 0x82, 0x8d, 0x40, 0, 0x60}, 0x8080: {0xa9, 0x82, 0, 0x8d, 0x41, 0, 0x60}, 0x8100: {0xdc, 0x40, 0}, 0x8210: {0x6b}})
	graphs := []*Graph{mustDecode(t, image, 0x8000, 0, 0), mustDecode(t, image, 0x8080, 0, 0), mustDecode(t, image, 0x8100, 0, 0)}
	if got := LiteralLongPointerTargets(image, graphs, nil); len(got) != 0 {
		t.Fatalf("mixed separate producers: %X", got)
	}
}
