import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const context=vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../tools/action_editor/mobile/camera.js',import.meta.url),'utf8'),context);
const camera=vm.runInContext('ActionAuditCamera',context);
const view={x:200,y:100,yaw:0,pitch:0,zoom:1};
const a=camera.sample(new Map([[1,{x:100,y:100}]]));
const b=camera.sample(new Map([[1,{x:140,y:120}]]));
let next=camera.move(view,a,b,2);
assert.equal(next.x,120);assert.equal(next.y,60);assert.equal(next.yaw,0);assert.equal(next.pitch,0);
assert.equal(view.x,200,'gesture must not mutate a frozen report/view');
next=camera.move(view,a,b,2,'pan');
assert.equal(next.x,120);assert.equal(next.y,60);assert.equal(next.zoom,1,'mouse/2D override still pans');
next=camera.move(view,a,b,2,'orbit');
assert.equal(next.x,200);assert.equal(next.yaw,.2);assert.equal(next.pitch,.1,'mouse drag still orbits');
const pair1=camera.sample(new Map([[1,{x:100,y:100}],[2,{x:200,y:100}]]));
const pair2=camera.sample(new Map([[1,{x:100,y:100}],[2,{x:300,y:100}]]));
next=camera.move(view,pair1,pair2,2);
assert.equal(next.zoom,.5,'spreading fingers zooms in');assert.equal(next.x,200,'two fingers preserve the map position');
assert.equal(next.yaw,.25,'two fingers orbit without selecting a tool');
next=camera.move(view,pair1,pair2,2,'pan');
assert.equal(next.x,100);assert.equal(next.yaw,0,'Original 2D never orbits');
const symmetric=camera.sample(new Map([[1,{x:50,y:100}],[2,{x:250,y:100}]]));
next=camera.move(view,pair1,symmetric,2);
assert.equal(next.zoom,.5);assert.equal(next.yaw,0);assert.equal(next.x,200,'centered pinch only zooms');
next=camera.move(view,pair1,b,2);
assert.deepEqual(JSON.parse(JSON.stringify(next)),view,'lifting a finger rebases without moving the camera');
assert.equal(camera.sample(new Map()),null,'cancel leaves no active gesture');
const palm={x:200,y:200,span:100,count:3};
assert.deepEqual(JSON.parse(JSON.stringify(camera.move(view,palm,{...palm,x:400},2))),view,'extra fingers do not move the view');
const huge={x:10000,y:10000,span:100000,count:2};
assert.equal(camera.move(view,pair1,huge,1).zoom,.5,'pinch zoom is bounded');
assert.equal(camera.move(view,pair1,huge,1).yaw,.7);
const portrait=camera.outputSize(390,680),landscape=camera.outputSize(844,260);
assert.equal(portrait.height,768);assert.equal(landscape.width,768);
assert.ok(portrait.width<=768&&landscape.height<=768,'phone DPR cannot inflate the render budget');
const rect={left:20,top:30,width:400,height:400};
assert.equal(camera.canvasPoint(rect,800,400,30,50),null,'letterbox taps cannot pin an unrelated face');
const point=camera.canvasPoint(rect,800,400,220,230);
assert.equal(point.x,400);assert.equal(point.y,200);
const support=new Uint8Array(32*48);
support.fill(31,20*32,20*32+16);support.fill(31,10*32,10*32+4);
assert.equal(camera.initialY(support,32,48),152,'broad entrance floor wins over small ledges and empty bottom padding');
assert.equal(camera.initialY(new Uint8Array(256),16,16),0,'rooms without native floor support have a safe fallback');
const travel={minX:16,maxX:1024,maxY:800};
let bounds=camera.inspectionBounds(travel);
assert.equal(bounds.minX,-240);assert.equal(bounds.minY,-224);
assert.equal(bounds.maxX,1280);assert.equal(bounds.maxY,1024,'all four edges can be centered beyond gameplay scroll limits');
assert.equal(bounds.maxX-travel.maxX,256,'inspection padding does not depend on the render mode');
console.log('Audit camera: pan, orbit, pinch, pointer rebasing/cancel, render budget and letterbox picking passed');
